test('signed-in user B gets HTTP 404 for user A’s project', async ({ page }) => {
  test.skip(process.env.COSTLENS_LOCAL_AUTH_E2E !== '1', 'Requires real local Supabase users');
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL!;
  expect(['localhost', '127.0.0.1']).toContain(new URL(url).hostname);
  const options = { auth: { persistSession: false, autoRefreshToken: false } };
  const admin = createClient(url, process.env.SUPABASE_SERVICE_ROLE_KEY!, options);
  const clientA = createClient(url, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!, options);
  const run = randomUUID();
  const password = randomBytes(24).toString('base64url');
  const userIds: string[] = [];
  try {
    for (const label of ['a', 'b']) {
      const { data, error } = await admin.auth.admin.createUser({ email: `costlens-access-${run}-${label}@example.com`, password, email_confirm: true });
      expect(error).toBeNull();
      userIds.push(data.user!.id);
    }
    expect((await clientA.auth.signInWithPassword({ email: `costlens-access-${run}-a@example.com`, password })).error).toBeNull();
    const project = await clientA.from('projects').insert({ owner_id: userIds[0], name: `Private A project ${run}`, currency: 'USD' }).select('id').single();
    expect(project.error).toBeNull();
    await page.goto('/login');
    await page.getByLabel('Email', { exact: true }).fill(`costlens-access-${run}-b@example.com`);
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await expect(page).toHaveURL(/\/projects$/);
    const response = await page.goto(`/projects/${project.data!.id}`);
    expect(response?.status()).toBe(404);
    await expect(page).toHaveURL(new RegExp(`/projects/${project.data!.id}$`));
    await expect(page.getByText('This page could not be found.')).toBeVisible();
    await expect(page.getByText(`Private A project ${run}`, { exact: true })).not.toBeVisible();
  } finally {
    for (const id of userIds) expect((await admin.auth.admin.deleteUser(id)).error).toBeNull();
  }
});
